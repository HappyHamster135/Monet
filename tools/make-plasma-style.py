def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def write_style(out, ident, name, description, solid=False):
    out.mkdir(parents=True, exist_ok=True)
    for frame, spec in FRAMES.items():
        if solid:
            spec = dict(spec, glass=SOLID)
        svg = frame_svg(**spec)
        for folder in ("", "translucent/"):
            write(out / f"{folder}{frame}.svg", svg)
        # When a window touches the islands, Plasma draws them from solid/;
        # without compositing (no see-through, no shadows), from opaque/.
        write(out / f"solid/{frame}.svg", frame_svg(**dict(spec, glass=SOLID)))
        write(out / f"opaque/{frame}.svg", frame_svg(**dict(spec, glass=1), shadow=False))
    for frame, draw in CONTROLS.items():
        write(out / f"{frame}.svg", draw())
    # The frosted look: blur plus the painting's color brought up through the
    # glass. Plasma 6 reads it from metadata.json, older ones from plasmarc.
    contrast = {"enabled": True, "contrast": 0.18, "intensity": 1.05, "saturation": 1.7}
    (out / "metadata.json").write_text(json.dumps({
        "AdaptiveTransparency": {"enabled": True},
        "BlurBehindEffect": {"enabled": True},
        "ContrastEffect": contrast,
        "KPlugin": {
            "Authors": [{"Name": "Monet"}],
            "Description": description,
            "EnabledByDefault": True,
            "Id": ident,
            "License": "GPL-3.0-or-later",
            "Name": name,
            "Version": VERSION,
        },
        "X-Plasma-API": "5.0",
    }, indent=4) + "\n")
    (out / "plasmarc").write_text(f"""[ContrastEffect]
enabled=true
contrast={contrast["contrast"]}
intensity={contrast["intensity"]}
saturation={contrast["saturation"]}

[AdaptiveTransparency]
enabled=true

[BlurBehindEffect]
enabled=true
""")
    print("wrote", out.relative_to(ROOT))


def main():
    write_style(OUT, "monet", "Monet", "Glass islands and popovers over the painting")
    write_style(OUT.parent / "monet-solid", "monet-solid", "Monet (solid)",
                "Monet's islands and popovers without the glass", solid=True)


if __name__ == "__main__":
    main()
