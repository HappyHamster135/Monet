"""Draws Monet's Plasma style: the glass of the bar islands, popovers and tooltips.

Plasma draws panels and popovers from SVG frames cut into nine pieces. Here
each frame is a rounded rectangle of see-through color (KWin blurs the
painting behind it), a hairline edge, a line of light along the top, and a
soft shadow that sits a little below, like the islands in the design.

Colors come from the color scheme (MonetLight or MonetDark), so one style
serves mist and smoke. Everything not drawn here falls back to Breeze.

Run from the repository root:  python3 tools/make-plasma-style.py
"""

import base64
import io
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "linux" / "share" / "plasma" / "desktoptheme" / "monet"

# name: radius, content margin, shadow blur, shadow drop, shadow strength, glass opacity
FRAMES = {
    "dialogs/background": dict(radius=20, margin=10, blur=14, drop=8, strength=0.34, glass=0.50),
    "widgets/panel-background": dict(radius=22, margin=8, blur=12, drop=7, strength=0.32, glass=0.40),
    "widgets/tooltip": dict(radius=12, margin=8, blur=8, drop=4, strength=0.24, glass=0.66),
}

STYLE = """<style type="text/css" id="current-color-scheme">
.ColorScheme-Background { color:#f3f1ec; }
.ColorScheme-Text { color:#1c1b19; }
</style>"""


class Sheet:
    def __init__(self):
        self.parts = []
        self.x = 0
        self.y = 0
        self.row = 0

    def place(self, w, h):
        if self.x + w > 900:
            self.x = 0
            self.y += self.row + 6
            self.row = 0
        x, y = self.x, self.y
        self.x += w + 6
        self.row = max(self.row, h)
        return x, y

    def element(self, ident, w, h, body):
        x, y = self.place(w, h)
        clear = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="#000000" fill-opacity="0"/>'
        self.parts.append(f'<g id="{ident}">{clear}{body(x, y)}</g>')

    def hint(self, ident, w, h):
        x, y = self.place(max(w, 1), max(h, 1))
        self.parts.append(f'<rect id="{ident}" x="{x}" y="{y}" width="{w}" height="{h}" fill="#ff00ff"/>')

    def svg(self):
        h = self.y + self.row + 6
        return (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
                f'width="900" height="{h}" viewBox="0 0 900 {h}">\n'
                f"<!-- Monet glass. Generated by tools/make-plasma-style.py. -->\n<defs>{STYLE}</defs>\n"
                + "\n".join(self.parts) + "\n</svg>\n")


def quarter(cx, cy, start, end, r):
    return f"M{cx},{cy} L{start[0]},{start[1]} A{r},{r} 0 0 1 {end[0]},{end[1]} Z"


def ring(cx, cy, start, end, r, w):
    def at(p, radius):
        return (cx + (p[0] - cx) * radius / r, cy + (p[1] - cy) * radius / r)

    s0, e0, s1, e1 = at(start, r), at(end, r), at(start, r - w), at(end, r - w)
    return f"M{s0[0]},{s0[1]} A{r},{r} 0 0 1 {e0[0]},{e0[1]} L{e1[0]},{e1[1]} A{r - w},{r - w} 0 0 0 {s1[0]},{s1[1]} Z"


def corners(r):
    """Per corner: arc center and the arc's two ends, relative to an r x r piece."""
    return {
        "topleft": (r, r, (0, r), (r, 0)),
        "topright": (0, r, (0, 0), (r, r)),
        "bottomright": (0, 0, (r, 0), (0, r)),
        "bottomleft": (r, 0, (r, r), (0, 0)),
    }


def frame_pieces(sheet, prefix, r, glass, mask=False):
    """The glass itself: fill, hairline edge and the top line of light."""
    edge = 'class="ColorScheme-Text" fill="currentColor" fill-opacity="0.13"'
    fill = f'class="ColorScheme-Background" fill="currentColor" fill-opacity="{glass}"'
    if mask:
        fill = 'fill="#000000"'
    size = 24
    for which, (cx, cy, s, e) in corners(r).items():
        def body(x, y, cx=cx, cy=cy, s=s, e=e, which=which):
            shift = lambda p: (x + p[0], y + p[1])  # noqa: E731
            out = f'<path d="{quarter(x + cx, y + cy, shift(s), shift(e), r)}" {fill}/>'
            if not mask:
                out += f'<path d="{ring(x + cx, y + cy, shift(s), shift(e), r, 1)}" {edge}/>'
                if which.startswith("top"):
                    out += f'<path d="{ring(x + cx, y + cy, shift(s), shift(e), r - 1, 1)}" fill="#ffffff" fill-opacity="0.10"/>'
            return out
        sheet.element(prefix + which, r, r, body)
    for which in ("top", "bottom", "left", "right"):
        w, h = (size, r) if which in ("top", "bottom") else (r, size)

        def body(x, y, which=which, w=w, h=h):
            out = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" {fill}/>'
            if mask:
                return out
            bar = {"top": (x, y, w, 1), "bottom": (x, y + h - 1, w, 1),
                   "left": (x, y, 1, h), "right": (x + w - 1, y, 1, h)}[which]
            out += f'<rect x="{bar[0]}" y="{bar[1]}" width="{bar[2]}" height="{bar[3]}" {edge}/>'
            if which == "top":
                out += f'<rect x="{x}" y="{y + 1}" width="{w}" height="1" fill="#ffffff" fill-opacity="0.22"/>'
            return out
        sheet.element(prefix + which, w, h, body)
    sheet.element(prefix + "center", size, size, lambda x, y: f'<rect x="{x}" y="{y}" width="{size}" height="{size}" {fill}/>')


def shadow_pieces(sheet, r, blur, drop, strength):
    """A soft shadow, lower than the glass, cut away under the glass itself."""
    reach = int(blur * 2.6)
    top, bottom, side = max(reach - drop, 2), reach + drop, reach
    middle = 160
    k = 2  # draw at twice the size, then shrink, for smooth curves
    W = (side + r) * 2 + middle
    H = top + bottom + r * 2 + middle
    big = Image.new("L", (W * k, H * k), 0)
    from PIL import ImageDraw
    d = ImageDraw.Draw(big)
    box = [side * k, top * k, (W - side) * k - 1, (H - bottom) * k - 1]
    shadow_box = [box[0], box[1] + drop * k, box[2], box[3] + drop * k]
    d.rounded_rectangle(shadow_box, radius=r * k, fill=255)
    soft = big.filter(ImageFilter.GaussianBlur(blur * k / 2)).resize((W, H), Image.LANCZOS)
    glass = Image.new("L", (W * k, H * k), 0)
    ImageDraw.Draw(glass).rounded_rectangle(box, radius=r * k, fill=255)
    glass = glass.resize((W, H), Image.LANCZOS)
    alpha = np.asarray(soft).astype(np.float32) * strength
    alpha *= 1 - np.asarray(glass).astype(np.float32) / 255
    rgba = np.zeros((H, W, 4), np.uint8)
    rgba[..., 3] = np.clip(alpha, 0, 255).astype(np.uint8)
    img = Image.fromarray(rgba, "RGBA")

    def png(crop):
        buf = io.BytesIO()
        img.crop(crop).save(buf, "PNG", optimize=True)
        return base64.b64encode(buf.getvalue()).decode()

    x0, x1 = side + r, W - side - r
    y0, y1 = top + r, H - bottom - r
    mx, my = W // 2, H // 2
    pieces = {
        "shadow-topleft": (0, 0, x0, y0),
        "shadow-topright": (x1, 0, W, y0),
        "shadow-bottomleft": (0, y1, x0, H),
        "shadow-bottomright": (x1, y1, W, H),
        "shadow-top": (mx, 0, mx + 4, y0),
        "shadow-bottom": (mx, y1, mx + 4, H),
        "shadow-left": (0, my, x0, my + 4),
        "shadow-right": (x1, my, W, my + 4),
    }
    for ident, crop in pieces.items():
        w, h = crop[2] - crop[0], crop[3] - crop[1]
        data = png(crop)
        sheet.element(ident, w, h, lambda x, y, w=w, h=h, data=data:
                      f'<image x="{x}" y="{y}" width="{w}" height="{h}" xlink:href="data:image/png;base64,{data}"/>')
    sheet.element("shadow-center", 4, 4, lambda x, y: "")
    sheet.hint("shadow-hint-top-margin", 2, top)
    sheet.hint("shadow-hint-bottom-margin", 2, bottom)
    sheet.hint("shadow-hint-left-margin", side, 2)
    sheet.hint("shadow-hint-right-margin", side, 2)


def frame_svg(radius, margin, blur, drop, strength, glass):
    sheet = Sheet()
    frame_pieces(sheet, "", radius, glass)
    frame_pieces(sheet, "mask-", radius, glass, mask=True)
    shadow_pieces(sheet, radius, blur, drop, strength)
    sheet.hint("hint-top-margin", 4, margin)
    sheet.hint("hint-bottom-margin", 4, margin)
    sheet.hint("hint-left-margin", margin, 4)
    sheet.hint("hint-right-margin", margin, 4)
    return sheet.svg()


def write_style(out, ident, name, description, solid=False):
    out.mkdir(parents=True, exist_ok=True)
    for frame, spec in FRAMES.items():
        if solid:
            spec = dict(spec, glass=0.96)
        svg = frame_svg(**spec)
        for folder in ("", "translucent/"):
            path = out / f"{folder}{frame}.svg"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(svg)
    (out / "metadata.json").write_text(json.dumps({
        "KPlugin": {
            "Authors": [{"Name": "Monet"}],
            "Description": description,
            "EnabledByDefault": True,
            "Id": ident,
            "License": "GPL-3.0-or-later",
            "Name": name,
            "Version": "0.6.0",
        },
        "X-Plasma-API": "5.0",
    }, indent=4) + "\n")
    # The frosted look: blur plus a little extra color and contrast.
    (out / "plasmarc").write_text("""[ContrastEffect]
enabled=true
contrast=0.18
intensity=1.05
saturation=1.5

[AdaptiveTransparency]
enabled=true

[BlurBehindEffect]
enabled=true
""")
    print("wrote", out.relative_to(ROOT))


def main():
    write_style(OUT, "monet", "Monet", "Glass islands and popovers over the painting")
    write_style(OUT.parent / "monet-solid", "monet-solid", "Monet (solid)",
                "Monet's islands and popovers without the glass", solid=True)


if __name__ == "__main__":
    main()
