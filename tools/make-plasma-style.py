class Sheet:
    def __init__(self, defs=""):
        self.parts = []
        self.x = 0
        self.y = 0
        self.row = 0
        self.defs = defs

    def place(self, w, h):
        if self.x + w > 900:
            self.x = 0
            self.y += self.row + 6
            self.row = 0
        x, y = self.x, self.y
        self.x += w + 6
        self.row = max(self.row, h)
        return x, y

    def element(self, ident, w, h, body):
        x, y = self.place(w, h)
        clear = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="#000000" fill-opacity="0"/>'
        self.parts.append(f'<g id="{ident}">{clear}{body(x, y)}</g>')

    def hint(self, ident, w, h):
        x, y = self.place(max(w, 1), max(h, 1))
        self.parts.append(f'<rect id="{ident}" x="{x}" y="{y}" width="{w}" height="{h}" fill="#ff00ff"/>')

    def svg(self):
        h = self.y + self.row + 6
        return (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
                f'width="900" height="{h}" viewBox="0 0 900 {h}">\n'
                f"<!-- Monet glass. Generated by tools/make-plasma-style.py. -->\n<defs>{STYLE}{self.defs}</defs>\n"
                + "\n".join(self.parts) + "\n</svg>\n")


def along(cx, cy, p, radius):
    """p slid along its ray from the arc's centre onto radius: start and end lie on the
    piece's own arc, and every band inside it must share that arc's centre."""
    d = math.hypot(p[0] - cx, p[1] - cy)
    return (cx + (p[0] - cx) * radius / d, cy + (p[1] - cy) * radius / d)


def quarter(cx, cy, start, end, r):
    s, e = along(cx, cy, start, r), along(cx, cy, end, r)
    return f"M{cx},{cy} L{s[0]},{s[1]} A{r},{r} 0 0 1 {e[0]},{e[1]} Z"


def ring(cx, cy, start, end, r, w):
    s0, e0, s1, e1 = (along(cx, cy, p, q) for p, q in ((start, r), (end, r), (start, r - w), (end, r - w)))
    return f"M{s0[0]},{s0[1]} A{r},{r} 0 0 1 {e0[0]},{e0[1]} L{e1[0]},{e1[1]} A{r - w},{r - w} 0 0 0 {s1[0]},{s1[1]} Z"


def corners(r):
    """Per corner: arc center and the arc's two ends, relative to an r x r piece."""
    return {
        "topleft": (r, r, (0, r), (r, 0)),
        "topright": (0, r, (0, 0), (r, r)),
        "bottomright": (0, 0, (r, 0), (0, r)),
        "bottomleft": (r, 0, (r, r), (0, 0)),
    }


# Light in the glass: a rim brightest along the top that fades down the sides,
# the way light gathers in the thickness of a pane, and a soft sheen under it.
RIM_TOP, RIM_BOTTOM, SHEEN = 0.34, 0.05, 0.12
GRADIENTS = (f'<linearGradient id="rim-fall" x1="0" y1="0" x2="0" y2="1">'
             f'<stop offset="0" stop-color="#ffffff" stop-opacity="{RIM_TOP}"/>'
             f'<stop offset="1" stop-color="#ffffff" stop-opacity="{RIM_BOTTOM}"/></linearGradient>'
             f'<linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">'
             f'<stop offset="0" stop-color="#ffffff" stop-opacity="{SHEEN}"/>'
             f'<stop offset="1" stop-color="#ffffff" stop-opacity="0"/></linearGradient>')


def frame_pieces(sheet, prefix, r, glass, mask=False):
    """The glass itself: fill, hairline edge, the rim of light and its sheen.
    The sides stretch (hint-stretch-borders), so the rim fades over the
    frame's whole height."""
    edge = 'class="ColorScheme-Text" fill="currentColor" fill-opacity="0.13"'
    fill = f'class="ColorScheme-Background" fill="currentColor" fill-opacity="{glass}"'
    if mask:
        fill = 'fill="#000000"'
    size = 24
    for which, (cx, cy, s, e) in corners(r).items():
        def body(x, y, cx=cx, cy=cy, s=s, e=e, which=which):
            shift = lambda p: (x + p[0], y + p[1])  # noqa: E731
            # KWin blurs every pixel the mask touches, whole: the mask's corner sits 1 px
            # inside the glass's (as in Breeze) so the blur stays under its soft edge.
            out = f'<path d="{quarter(x + cx, y + cy, shift(s), shift(e), r - 1 if mask else r)}" {fill}/>'
            if not mask:
                top = which.startswith("top")
                if top:  # under the hairline and the rim, as on the top edge (y + 2)
                    out += f'<path d="{quarter(x + cx, y + cy, shift(s), shift(e), r - 2)}" fill="url(#sheen)"/>'
                out += f'<path d="{ring(x + cx, y + cy, shift(s), shift(e), r, 1)}" {edge}/>'
                out += (f'<path d="{ring(x + cx, y + cy, shift(s), shift(e), r - 1, 1)}" fill="#ffffff" '
                        f'fill-opacity="{RIM_TOP if top else RIM_BOTTOM}"/>')
            return out
        sheet.element(prefix + which, r, r, body)
    for which in ("top", "bottom", "left", "right"):
        w, h = (size, r) if which in ("top", "bottom") else (r, size)

        def body(x, y, which=which, w=w, h=h):
            out = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" {fill}/>'
            if mask:
                return out
            if which == "top":
                out += f'<rect x="{x}" y="{y + 2}" width="{w}" height="{h - 2}" fill="url(#sheen)"/>'
            bar = {"top": (x, y, w, 1), "bottom": (x, y + h - 1, w, 1),
                   "left": (x, y, 1, h), "right": (x + w - 1, y, 1, h)}[which]
            out += f'<rect x="{bar[0]}" y="{bar[1]}" width="{bar[2]}" height="{bar[3]}" {edge}/>'
            rim = {"top": (x, y + 1, w, 1, f'fill="#ffffff" fill-opacity="{RIM_TOP}"'),
                   "bottom": (x, y + h - 2, w, 1, f'fill="#ffffff" fill-opacity="{RIM_BOTTOM}"'),
                   "left": (x + 1, y, 1, h, 'fill="url(#rim-fall)"'),
                   "right": (x + w - 2, y, 1, h, 'fill="url(#rim-fall)"')}[which]
            out += f'<rect x="{rim[0]}" y="{rim[1]}" width="{rim[2]}" height="{rim[3]}" {rim[4]}/>'
            return out
        sheet.element(prefix + which, w, h, body)
    sheet.element(prefix + "center", size, size, lambda x, y: f'<rect x="{x}" y="{y}" width="{size}" height="{size}" {fill}/>')


def shadow_pieces(sheet, r, blur, drop, strength):
    """A soft shadow, lower than the glass, cut away under the glass itself."""
    reach = int(blur * 2.6)
    top, bottom, side = max(reach - drop, 2), reach + drop, reach
    middle = 160
    k = 2  # draw at twice the size, then shrink, for smooth curves
    W = (side + r) * 2 + middle
    H = top + bottom + r * 2 + middle
    big = Image.new("L", (W * k, H * k), 0)
    d = ImageDraw.Draw(big)
    box = [side * k, top * k, (W - side) * k - 1, (H - bottom) * k - 1]
    shadow_box = [box[0], box[1] + drop * k, box[2], box[3] + drop * k]
    d.rounded_rectangle(shadow_box, radius=r * k, fill=255)
    soft = big.filter(ImageFilter.GaussianBlur(blur * k / 2)).resize((W, H), Image.LANCZOS)
    c = 8  # the cut must follow the glass's antialiased edge: finer, and averaged (no ringing)
    glass = Image.new("L", (W * c, H * c), 0)
    ImageDraw.Draw(glass).rounded_rectangle([side * c, top * c, (W - side) * c - 1, (H - bottom) * c - 1], radius=r * c, fill=255)
    glass = glass.resize((W, H), Image.BOX)
    alpha = np.asarray(soft).astype(np.float32) * strength
    alpha *= 1 - np.asarray(glass).astype(np.float32) / 255
    rgba = np.zeros((H, W, 4), np.uint8)
    rgba[..., 3] = np.clip(alpha, 0, 255).astype(np.uint8)
    img = Image.fromarray(rgba, "RGBA")

    x0, x1 = side + r, W - side - r
    y0, y1 = top + r, H - bottom - r
    mx, my = W // 2, H // 2
    pieces = {
        "shadow-topleft": (0, 0, x0, y0),
        "shadow-topright": (x1, 0, W, y0),
        "shadow-bottomleft": (0, y1, x0, H),
        "shadow-bottomright": (x1, y1, W, H),
        "shadow-top": (mx, 0, mx + 4, y0),
        "shadow-bottom": (mx, y1, mx + 4, H),
        "shadow-left": (0, my, x0, my + 4),
        "shadow-right": (x1, my, W, my + 4),
    }
    for ident, crop in pieces.items():
        w, h = crop[2] - crop[0], crop[3] - crop[1]
        data = png(img.crop(crop))
        sheet.element(ident, w, h, lambda x, y, w=w, h=h, data=data: image(x, y, w, h, data))
    sheet.element("shadow-center", 4, 4, lambda x, y: "")
    sheet.hint("shadow-hint-top-margin", 2, top)
    sheet.hint("shadow-hint-bottom-margin", 2, bottom)
    sheet.hint("shadow-hint-left-margin", side, 2)
    sheet.hint("shadow-hint-right-margin", side, 2)


def png(img):
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def image(x, y, w, h, data):
    return f'<image x="{x}" y="{y}" width="{w}" height="{h}" xlink:href="data:image/png;base64,{data}"/>'


def frame_svg(radius, margin, blur, drop, strength, glass, shadow=True):
    sheet = Sheet(GRADIENTS)
    frame_pieces(sheet, "", radius, glass)
    frame_pieces(sheet, "mask-", radius, glass, mask=True)
    if shadow:
        shadow_pieces(sheet, radius, blur, drop, strength)
    sheet.hint("hint-top-margin", 4, margin)
    sheet.hint("hint-bottom-margin", 4, margin)
    sheet.hint("hint-left-margin", margin, 4)
    sheet.hint("hint-right-margin", margin, 4)
    sheet.hint("hint-stretch-borders", 4, 4)  # so the rim fades over the whole height
    return sheet.svg()


# Shapes for the controls ----------------------------------------------------
# Pieces are cut from one drawing of the whole control: each piece shows the
# part of the shapes inside its box, so corners, edges and middle always meet.

def rounded(x0, y0, x1, y1, r, steps=18):
    """A rounded rectangle's outline as points, clockwise."""
    r = max(0.0, min(r, (x1 - x0) / 2, (y1 - y0) / 2))
    out = []
    for cx, cy, start in ((x0 + r, y0 + r, 180), (x1 - r, y0 + r, 270), (x1 - r, y1 - r, 0), (x0 + r, y1 - r, 90)):
        for i in range(steps + 1):
            a = math.radians(start + 90 * i / steps)
            out.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return out


def disc(cx, cy, r, steps=72):
    return [(cx + r * math.cos(2 * math.pi * i / steps), cy + r * math.sin(2 * math.pi * i / steps)) for i in range(steps)]


def clip(points, box):
    """The part of a convex outline inside box (x0, y0, x1, y1)."""
    x0, y0, x1, y1 = box
    edges = ((lambda p: p[0] >= x0, lambda a, b: (x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0]))),
             (lambda p: p[0] <= x1, lambda a, b: (x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0]))),
             (lambda p: p[1] >= y0, lambda a, b: (a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0)),
             (lambda p: p[1] <= y1, lambda a, b: (a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1)))
    for inside, cut in edges:
        if not points:
            break
        kept, prev = [], points[-1]
        for cur in points:
            if inside(cur):
                if not inside(prev):
                    kept.append(cut(prev, cur))
                kept.append(cur)
            elif inside(prev):
                kept.append(cut(prev, cur))
            prev = cur
        points = kept
    return points


def outline(points, dx=0.0, dy=0.0):
    if len(points) < 3:
        return ""
    return "M" + " L".join(f"{x + dx:.3f},{y + dy:.3f}" for x, y in points) + " Z"


class Shape:
    """A filled outline, or a ring between two outlines, in one paint."""

    def __init__(self, paint, outer, inner=None):
        self.paint, self.outer, self.inner = paint, outer, inner

    def cut(self, box, dx, dy):
        d = outline(clip(self.outer, box), dx, dy)
        if not d:
            return ""
        if self.inner:
            d += " " + outline(clip(self.inner, box), dx, dy)
            return f'<path d="{d}" fill-rule="evenodd" {self.paint}/>'
        return f'<path d="{d}" {self.paint}/>'


def paint(how, opacity=1.0):
    return f'{how} fill-opacity="{opacity:g}"' if opacity < 1 else how


def fill(how, opacity, size, inset=0.0, radius=0.0):
    w, h = size
    return Shape(paint(how, opacity), rounded(inset, inset, w - inset, h - inset, radius))


def band(how, opacity, size, inset, radius, width):
    """A ring of the given width just inside a rounded rectangle."""
    w, h = size
    return Shape(paint(how, opacity), rounded(inset, inset, w - inset, h - inset, radius),
                 rounded(inset + width, inset + width, w - inset - width, h - inset - width, radius - width))


def nine(sheet, prefix, borders, shapes, middle=8, margins=None):
    """A frame's nine pieces (corners, edges, middle) cut from one drawing.

    borders: (left, top, right, bottom); shapes are drawn on a frame of the
    smallest size, so the edges in between are uniform and can be tiled.
    middle is the middle piece's size, or (width, height)."""
    left, top, right, bottom = borders
    mw, mh = middle if isinstance(middle, tuple) else (middle, middle)
    w, h = left + mw + right, top + mh + bottom
    name = prefix + "-" if prefix else ""
    xs, ys = (0, left, left + mw, w), (0, top, top + mh, h)
    grid = {"topleft": (0, 0), "top": (1, 0), "topright": (2, 0), "left": (0, 1), "center": (1, 1),
            "right": (2, 1), "bottomleft": (0, 2), "bottom": (1, 2), "bottomright": (2, 2)}
    for piece, (i, j) in grid.items():
        box = (xs[i], ys[j], xs[i + 1], ys[j + 1])
        pw, ph = box[2] - box[0], box[3] - box[1]
        if pw <= 0 or ph <= 0:
            continue
        sheet.element(name + piece, pw, ph,
                      lambda x, y, box=box: "".join(s.cut(box, x - box[0], y - box[1]) for s in shapes))
    for side, value in zip(("left", "top", "right", "bottom"), margins or ()):
        sheet.hint(f"{name}hint-{side}-margin", *((value, 2) if side in ("left", "right") else (2, value)))
    return w, h


def drawing(shapes, w, h):
    """A plain element: the shapes, placed in its box."""
    return lambda x, y: "".join(s.cut((0, 0, w, h), x, y) for s in shapes)


def blurred_disc(size, r, drop, blur, strength):
    """A soft round shadow, as a PNG to place under a knob."""
    k = 4
    img = Image.new("L", (size * k, size * k), 0)
    c = size * k / 2
    ImageDraw.Draw(img).ellipse([c - r * k, c - r * k + drop * k, c + r * k, c + r * k + drop * k], fill=255)
    img = img.filter(ImageFilter.GaussianBlur(blur * k)).resize((size, size), Image.LANCZOS)
    alpha = (np.asarray(img).astype(np.float32) * strength).astype(np.uint8)
    rgba = np.zeros((size, size, 4), np.uint8)
    rgba[..., 3] = alpha
    return png(Image.fromarray(rgba, "RGBA"))


