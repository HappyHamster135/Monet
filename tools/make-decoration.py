"""Draws Monet's window frames: a title bar of the same glass as the window
below it, a soft ink shadow, and buttons brushed in ink. Under the pointer a
dab of paint swells up beneath the sign: lily to tuck the window away, ochre
to fill the screen, the sun's vermilion to close.

Writes KWin (Aurorae) themes to linux/share/aurorae/themes: Monet (mist) and
MonetSmoke, each with glass and solid, picked by monet-light like the rest.

Run from the repository root:  python3 tools/make-decoration.py
"""

import base64
import importlib.util
import io
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "linux" / "share" / "aurorae" / "themes"
VERSION = (ROOT / "VERSION").read_text().strip()

# The frame, in pixels at 100%: shadow room around the window, the glass
# border, the title bar, and the corners' radii.
SIDE, TOP, BOTTOM = 40, 30, 54
BORDER = 4
EDGE_TOP, TITLE, EDGE_BOTTOM = 5, 26, 5
BAR = EDGE_TOP + TITLE + EDGE_BOTTOM
RADIUS, RADIUS_BOTTOM = 14, 10
MIDDLE = 24
BUTTON = 26
K = 3  # pictures are kept at three times the size, sharp on HiDPI screens

# Glass and ink as in the app style (tools/make-kvantum.py), so the title bar
# runs into the window without a seam.
LIGHTS = {
    "Monet": dict(name="Monet Mist", glass=(247, 245, 241, 196), solid=(243, 241, 236, 255), text="28,27,25",
                  dim="107,102,94", line=(0, 0, 0, 26), rim=(255, 255, 255, 120), sign=(28, 27, 25, 200),
                  sign_dim=(107, 102, 94, 170)),
    "MonetSmoke": dict(name="Monet Smoke", glass=(34, 33, 31, 196), solid=(36, 35, 33, 255), text="239,236,230",
                       dim="180,174,165", line=(255, 255, 255, 26), rim=(255, 255, 255, 30),
                       sign=(239, 236, 230, 215), sign_dim=(180, 174, 165, 160)),
}
INK = (28, 27, 25)
ON_PAINT = (28, 27, 25, 205)  # the sign over a dab, in either light

# Button: its dab's paint (and the odd stroke of another color), and its sign.
BUTTONS = {
    "minimize": ("#3F9A89", ["#7CD3C0", "#2A6A5F", "#5C88D0"], "bar"),
    "maximize": ("#E8AE48", ["#F6D58A", "#C98A2E", "#FFC46B"], "square"),
    "restore": ("#E8AE48", ["#F6D58A", "#C98A2E", "#FFC46B"], "squares"),
    "close": ("#F2552C", ["#FFC46B", "#FF7A4A", "#D9361A", "#FF8FA0"], "cross"),
}


