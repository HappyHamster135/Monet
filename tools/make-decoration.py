def png(img):
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def image(x, y, w, h, img):
    return f'<image x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" xlink:href="data:image/png;base64,{png(img)}"/>'


class Sheet:
    """SVG elements side by side, so their boxes never overlap."""

    def __init__(self, comment):
        self.parts, self.x, self.y, self.row, self.comment = [], 0, 0, 0, comment

    def element(self, ident, w, h, body):
        if self.x + w > 600:
            self.x, self.y, self.row = 0, self.y + self.row + 4, 0
        x, y = self.x, self.y
        self.x += w + 4
        self.row = max(self.row, h)
        clear = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="#000000" fill-opacity="0"/>'
        self.parts.append(f'<g id="{ident}">{clear}{body(x, y)}</g>')

    def svg(self):
        h = self.y + self.row + 4
        return (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
                f'width="600" height="{h}" viewBox="0 0 600 {h}">\n'
                f"<!-- {self.comment} Generated by tools/make-decoration.py. -->\n" + "\n".join(self.parts) + "\n</svg>\n")


# The frame ----------------------------------------------------------------
# The glass is drawn with shapes, cut to each piece, so pieces meet without a
# seam; only the soft shadow is a picture.

def outline(x0, y0, x1, y1, top, bottom, steps=18):
    """The window's outline, clockwise: rounder at the top than at the bottom."""
    out = []
    for cx, cy, r, start in ((x0 + top, y0 + top, top, 180), (x1 - top, y0 + top, top, 270),
                             (x1 - bottom, y1 - bottom, bottom, 0), (x0 + bottom, y1 - bottom, bottom, 90)):
        for i in range(steps + 1):
            a = math.radians(start + 90 * i / steps)
            out.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return out


def clip(points, box):
    """The part of a convex outline inside box (x0, y0, x1, y1)."""
    x0, y0, x1, y1 = box
    edges = ((lambda p: p[0] >= x0, lambda a, b: (x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0]))),
             (lambda p: p[0] <= x1, lambda a, b: (x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0]))),
             (lambda p: p[1] >= y0, lambda a, b: (a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0)),
             (lambda p: p[1] <= y1, lambda a, b: (a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1)))
    for inside, cut in edges:
        kept, prev = [], points[-1] if points else None
        for cur in points:
            if inside(cur):
                if not inside(prev):
                    kept.append(cut(prev, cur))
                kept.append(cur)
            elif inside(prev):
                kept.append(cut(prev, cur))
            prev = cur
        points = kept
    return points


def path(points, dx, dy):
    return "M" + " L".join(f"{x + dx:.2f},{y + dy:.2f}" for x, y in points) + " Z" if len(points) > 2 else ""


def paint(rgba):
    return f'fill="#{rgba[0]:02X}{rgba[1]:02X}{rgba[2]:02X}" fill-opacity="{rgba[3] / 255:.3g}"'


def frame_size():
    margins = (SIDE + RADIUS, TOP + BAR, SIDE + RADIUS, RADIUS_BOTTOM + BOTTOM)
    return margins, margins[0] + MIDDLE + margins[2], margins[1] + MIDDLE + margins[3]


def shadow_image(active):
    """The soft ink shadow, a little below the window; none under the glass."""
    _, w, h = frame_size()
    blur, drop, strength = (16, 10, 0.48) if active else (10, 6, 0.26)
    glass, lifted = Image.new("L", (w * K, h * K), 0), Image.new("L", (w * K, h * K), 0)
    for img, dy in ((glass, 0), (lifted, drop)):
        d = ImageDraw.Draw(img)
        d.polygon([(x * K, (y + dy) * K) for x, y in outline(SIDE, TOP, w - SIDE, h - BOTTOM, RADIUS, RADIUS_BOTTOM)], fill=255)
    soft = np.asarray(lifted.filter(ImageFilter.GaussianBlur(blur * K / 2))).astype(np.float32) / 255
    rgba = np.zeros((h * K, w * K, 4), np.uint8)
    rgba[..., :3] = INK
    rgba[..., 3] = np.clip(soft * strength * (1 - np.asarray(glass) / 255) * 255, 0, 255).astype(np.uint8)
    return Image.fromarray(rgba, "RGBA")


def frame(sheet, prefix, light, active, solid, mask=False):
    """The nine pieces: each shows the part of the shadow and the glass inside its box."""
    (left, top, right, bottom), w, h = frame_size()
    spec = LIGHTS[light]
    body = outline(SIDE, TOP, w - SIDE, h - BOTTOM, RADIUS, RADIUS_BOTTOM)
    inside = outline(SIDE + 1, TOP + 1, w - SIDE - 1, h - BOTTOM - 1, RADIUS - 1, RADIUS_BOTTOM - 1)
    rim = [(SIDE + RADIUS, TOP + 1), (w - SIDE - RADIUS, TOP + 1), (w - SIDE - RADIUS, TOP + 2), (SIDE + RADIUS, TOP + 2)]
    rim_color = spec["rim"] if active else spec["rim"][:3] + (spec["rim"][3] * 3 // 5,)
    layers = [(body, None, 'fill="#000000"')] if mask else [
        (body, None, paint(spec["solid" if solid else "glass"])),
        (body, inside, paint(spec["line"])),  # the hairline edge
        (rim, None, paint(rim_color)),        # light along the top
    ]
    shadow = None if mask else shadow_image(active)
    xs, ys = (0, left, w - right, w), (0, top, h - bottom, h)
    names = ("topleft", "top", "topright", "left", "center", "right", "bottomleft", "bottom", "bottomright")
    for n, piece in enumerate(names):
        i, j = n % 3, n // 3
        box = (xs[i], ys[j], xs[i + 1], ys[j + 1])
        pw, ph = box[2] - box[0], box[3] - box[1]

        def draw(x, y, box=box, pw=pw, ph=ph, piece=piece):
            if piece == "center":
                return ""  # behind the window itself
            dx, dy = x - box[0], y - box[1]
            out = image(x, y, pw, ph, shadow.crop(tuple(v * K for v in box))) if shadow else ""
            for outer, hole, how in layers:
                d = path(clip(outer, box), dx, dy)
                if d and hole:
                    d += " " + path(clip(hole, box), dx, dy)
                    out += f'<path d="{d}" fill-rule="evenodd" {how}/>'
                elif d:
                    out += f'<path d="{d}" {how}/>'
            return out
        sheet.element(f"{prefix}-{piece}", pw, ph, draw)


def flat(sheet, prefix, how):
    """Filling the screen: no corners, no shadow, only the glass."""
    for piece in ("topleft", "top", "topright", "left", "center", "right", "bottomleft", "bottom", "bottomright"):
        sheet.element(f"{prefix}-{piece}", 4, 4, lambda x, y: f'<rect x="{x}" y="{y}" width="4" height="4" {how}/>')


def decoration_svg(light, solid):
    sheet = Sheet(f"Monet's window frame, {LIGHTS[light]['name']}.")
    frame(sheet, "decoration", light, True, solid)
    frame(sheet, "decoration-inactive", light, False, solid)
    frame(sheet, "mask", light, True, solid, mask=True)
    glass = paint(LIGHTS[light]["solid" if solid else "glass"])
    flat(sheet, "decoration-maximized", glass)
    flat(sheet, "decoration-maximized-inactive", glass)
    flat(sheet, "mask-maximized", 'fill="#000000"')
    return sheet.svg()


# The buttons --------------------------------------------------------------

def paint_dab(mi, color, accents, seed, dark=1.0):
    """A dab of paint, the way it sits on the palette."""
    c = mi.Canvas(seed)
    outline = mi.poly(mi.ellipse(64, 61, 46, 43, c.rng.uniform(-20, 20), 60))
    base = mi.hexrgb(color) * dark
    hexed = "#" + "".join(f"{int(min(1, v) * 255):02X}" for v in base)
    # Few, broad strokes: at this size fine ones only read as glitter.
    c.paint(outline, mi.lit(hexed, hexed, light=0.3, shade=0.2), 11.0, mi.around(64, 61), layers=2, wander=0.3,
            jitter=0.03, accents=accents, accent_rate=0.08, thick=1.6)
    return c.finish(relief=1.1, shadow=0.16, size=BUTTON * K)


