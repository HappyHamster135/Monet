def sign(ps, kind, x, y, color):
    """The button's sign, brushed: a bar, a square, two squares, a cross."""
    b = ps.brush
    strokes = {
        "bar": [b([(9, 13.6), (17, 13.6)], 1.9, 0.35)],
        "square": [b([(9.2, 9.2), (16.8, 9.2), (16.8, 16.8), (9.2, 16.8), (9.2, 9.2)], 1.5, 0.15, smooth=False)],
        "squares": [b([(11.6, 8.4), (17.6, 8.4), (17.6, 14.4)], 1.3, 0.15, smooth=False),
                    b([(8.4, 11.6), (14.4, 11.6), (14.4, 17.6), (8.4, 17.6), (8.4, 11.6)], 1.4, 0.15, smooth=False)],
        "cross": [b([(9.2, 9.2), (16.8, 16.8)], 1.9, 0.35), b([(16.8, 9.2), (9.2, 16.8)], 1.9, 0.35)],
    }[kind]
    paint = f'fill="#{color[0]:02X}{color[1]:02X}{color[2]:02X}" fill-opacity="{color[3] / 255:.3g}"'
    return "".join(f'<path d="{ps.outline(points, x, y)}" {paint}/>' for points in strokes)


def button_svg(ps, kind, light, dabs):
    """At rest only the sign, in ink; with the pointer on it, its dab of paint
    swells up under the sign (never three colored circles in a row)."""
    mark = BUTTONS[kind][2]
    spec = LIGHTS[light]
    sheet = Sheet(f"Monet's {kind} button, {spec['name']}.")

    def state(sign_color, img=None, scale=1.0, faint=1.0):
        def body(x, y):
            out = ""
            if img is not None:
                s = BUTTON * scale
                out = image(x + (BUTTON - s) / 2, y + (BUTTON - s) / 2, s, s, img)
            color = sign_color[:3] + (int(sign_color[3] * faint),)
            return out + sign(ps, mark, x, y, color)
        return body

    near = state(ON_PAINT, dabs[kind], 0.96)
    down = state(ON_PAINT, dabs[kind + "-pressed"], 0.88)
    for name, body in (("active", state(spec["sign"])), ("hover", near), ("pressed", down),
                       ("deactivated", state(spec["sign"], faint=0.35)), ("inactive", state(spec["sign_dim"])),
                       ("hover-inactive", near), ("pressed-inactive", down),
                       ("deactivated-inactive", state(spec["sign_dim"], faint=0.35))):
        # Aurorae draws each state as a frame with only its center: "<state>-center".
        sheet.element(f"{name}-center", BUTTON, BUTTON, body)
    return sheet.svg()


